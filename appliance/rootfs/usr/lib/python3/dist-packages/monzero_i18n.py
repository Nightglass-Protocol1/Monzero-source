def from_accept(header):
    """The best language for a browser's Accept-Language header."""
    best, bq = "en", -1.0
    for part in (header or "").split(","):
        tag, _, q = part.strip().partition(";q=")
        code = tag.strip().lower().split("-")[0]
        try:
            qv = float(q) if q else 1.0
        except ValueError:
            qv = 0.0
        if code in LANGS and qv > bq:
            best, bq = code, qv
    return best


def qt_ini(value):
    """A value as Qt 5's QSettings writes it in an ini file (non-ASCII as \\xNNNN)."""
    out, after_escape = [], False
    for ch in value:
        o = ord(ch)
        if o >= 0x7F or o < 0x20 or (after_escape and ch in "0123456789abcdefABCDEF"):
            out.append("\\x%x" % o)
            after_escape = True
        else:
            out.append("\\\\" if ch == "\\" else '\\"' if ch == '"' else ch)
            after_escape = False
    s = "".join(out)
