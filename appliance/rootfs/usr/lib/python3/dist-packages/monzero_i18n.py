def set_wallet_language(conf_path, lang):
    """Point the wallet's own setting at this language (its config file, [General])."""
    loc, name = LANGS[norm(lang)][2]
    want = {"locale": loc, "language": qt_ini(name)}
    try:
        lines = open(conf_path, encoding="utf-8").read().splitlines()
    except OSError:
        lines = []
    if "[General]" not in lines:
        lines = ["[General]"] + lines
    start = lines.index("[General]") + 1
    end = next((i for i in range(start, len(lines)) if lines[i].startswith("[")), len(lines))
    section = [l for l in lines[start:end] if l.split("=", 1)[0] not in want and l.strip()]
    section += [f"{k}={v}" for k, v in want.items()]
    lines = lines[:start] + sorted(section) + ([""] if end < len(lines) else []) + lines[end:]
    import os
    os.makedirs(os.path.dirname(conf_path), exist_ok=True)
    tmp = conf_path + ".new"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    os.replace(tmp, conf_path)
